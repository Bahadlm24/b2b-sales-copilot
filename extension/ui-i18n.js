export function uiLanguage(preference = "auto") {
  if (preference === "en" || preference === "tr") return preference;
  const language = typeof navigator !== "undefined" ? String(navigator.language || "").toLowerCase() : "tr";
  return language.startsWith("en") ? "en" : "tr";
}

export function uiText(key, preference = "auto", vars = {}) {
  const language = uiLanguage(preference);
  const value = copy[language]?.[key] || copy.tr[key] || key;
  return String(value).replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? "" : String(vars[name])));
}

export function applySidepanelCopy(preference = "auto") {
  const language = uiLanguage(preference);
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = uiText(node.dataset.i18n, preference);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    node.innerHTML = uiText(node.dataset.i18nHtml, preference);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = uiText(node.dataset.i18nPlaceholder, preference);
  });
}
